/**
 * Ideology map layouts (the #/map page and the "Exact from here" panel on results).
 *
 * For each space (ideal positions, here-and-now positions, both together) and dimension (2, 3):
 * metric MDS on the symmetrised quiz distance, best of a classical start and seeded random starts,
 * then Procrustes-aligned so every layout shares the ideal 2D map's orientation (which keeps the
 * ideal ⇄ here-and-now morph meaningful). Reports Kruskal stress-1 and 3-nearest-neighbour keep.
 *
 * Deterministic: same catalogue, same output. map.json stores a hash of its inputs, and
 * tests/map.test.ts fails when it is stale. `just archetypes` reruns this after rebuilding vectors.
 *
 *   pnpm tsx scripts/map-layout.ts [--check]   (--check: exit 1 if map.json is stale, write nothing)
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { CATALOGUE } from '../src/data/archetypes'
import {
  LAYOUT_VERSION,
  SPACES,
  bestLayout,
  distanceMatrix,
  knnKeep,
  layoutInputs,
  mapPoints,
  orient2d,
  procrustes,
  spaceIndex,
  stress1,
  type Space,
} from '../src/engine/mapLayout'

const OUT = 'src/data/map.json'
const hash = createHash('sha256').update(layoutInputs(CATALOGUE)).digest('hex').slice(0, 16)

if (process.argv.includes('--check')) {
  const cur = JSON.parse(readFileSync(OUT, 'utf8')) as { inputHash?: string }
  if (cur.inputHash !== hash) {
    console.error(`${OUT} is stale (has ${cur.inputHash}, catalogue is ${hash}): run \`just map-layout\``)
    process.exit(1)
  }
  console.log(`${OUT} is current (${hash})`)
  process.exit(0)
}

const n = CATALOGUE.length
const pts = mapPoints(CATALOGUE)
const round = (x: number) => Math.round(x * 1e4) / 1e4

interface Layout {
  coords: number[][]
  stress: number
  knn3: number
  stressIdeal?: number
  stressNow?: number
}
const layouts: Partial<Record<`${Space}-${2 | 3}`, Layout>> = {}

for (const dim of [2, 3] as const) {
  const raw: Partial<Record<Space, number[][]>> = {}
  const D: Partial<Record<Space, number[][]>> = {}
  for (const [k, space] of SPACES.entries()) {
    D[space] = distanceMatrix(spaceIndex(space, n).map(i => pts[i]!))
    raw[space] = bestLayout(D[space]!, dim, 1234 + 10 * dim + k)
  }
  // Reference: the ideal layout (2D oriented for familiarity; 3D rotated onto the 2D one).
  let ideal: number[][]
  if (dim === 2) ideal = orient2d(raw.ideal!, CATALOGUE)
  else {
    const ref = layouts['ideal-2']!.coords.map(([x, y]) => [x!, y!, 0])
    const f = procrustes(raw.ideal!, ref)
    ideal = raw.ideal!.map(f)
  }
  const aligned: Record<Space, number[][]> = {
    ideal,
    // Here-and-now position i is matched to ideal position i.
    now: raw.now!.map(procrustes(raw.now!, ideal)),
    // The joint layout's ideal half is matched to the ideal layout.
    joint: raw.joint!.map(procrustes(raw.joint!.slice(0, n), ideal)),
  }
  for (const space of SPACES) {
    const X = aligned[space]
    const rec: Layout = { coords: X.map(r => r.map(round)), stress: round(stress1(X, D[space]!)), knn3: round(knnKeep(X, D[space]!)) }
    if (space === 'joint') {
      rec.stressIdeal = round(stress1(X, D.joint!, (i, j) => i < n && j < n))
      rec.stressNow = round(stress1(X, D.joint!, (i, j) => i >= n && j >= n))
    }
    layouts[`${space}-${dim}`] = rec
    console.log(`${space} ${dim}D: stress-1 ${rec.stress}, 3-NN kept ${(rec.knn3 * 100).toFixed(0)}%`)
  }
}

const out = {
  version: LAYOUT_VERSION,
  inputHash: hash,
  note: 'Generated by scripts/map-layout.ts (`just map-layout`). Do not edit.',
  slugs: CATALOGUE.map(a => a.slug),
  layouts,
}
writeFileSync(OUT, JSON.stringify(out) + '\n')
console.log(`wrote ${OUT} (${hash})`)
